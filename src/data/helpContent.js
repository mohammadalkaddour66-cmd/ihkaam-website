/* Helper: get category object for a given article slug */
export function getCategoryForArticle(slug) {
  return CATEGORIES.find(c => c.articles.includes(slug)) || null
}

/* Helper: get article object by slug */
export function getArticle(slug) {
  return ARTICLES[slug] || null
}

/* Helper: flat list of all articles for search */
export function getAllArticles() {
  return Object.values(ARTICLES)
}
