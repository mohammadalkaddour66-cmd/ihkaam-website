/* ══════════════════════════════════════════════════════════════════
   «تقديراً + سبب»: يكتب المدير السبب كما يخطر له، والكود يضبطه، فلا يحفظ أحدٌ قاعدة.
   كلها تصل إلى النتيجة نفسها: «لحفظ جزء عمّ كاملاً»:
     «حفظ جزء عمّ كاملاً»            ← تُضاف اللام
     «لحفظ جزء عمّ كاملاً»           ← فيها لام فلا تتكرر
     «تقديراً لحفظ جزء عمّ كاملاً»   ← تُحذف «تقديراً» لأن الأداة تكتبها
     «هذه الشهادة تقديراً لحفظ…»    ← كذلك
     «التميّز في التسميع.»           ← «للتميّز في التسميع» وتُحذف النقطة الأخيرة
   ══════════════════════════════════════════════════════════════════ */

/* كلمات تبدأ باللام أصلاً (ليست لام جر): تُضاف لها لام جر عادية */
const LAM_WORDS = /^(لغ|لسا|لياق|لباق|لطف|لقاء|لقب|ليل|لوح|لون)/

/* السبب كما كتبه المستخدم بلا لام ولا «تقديراً» ولا نقطة أخيرة: ما تُدرجه قطعة [الإنجاز] في الصيغة */
export function reasonPlain(raw) {
  let t = String(raw || '').trim()
  /* «هذه الشهادة» و«تقديراً» تكتبهما الأداة نفسها */
  t = t.replace(/^(?:هذه\s+الشهادة\s+)?تقدير(?:ا|ً)*\s*/u, '')
  /* النقطة والفاصلة في الآخر: الأداة تختم الجملة بنفسها */
  return t.replace(/[\s.،,؛:]+$/u, '').trim()
}

export function reasonWithLam(raw) {
  const t = reasonPlain(raw)
  if (!t) return ''
  if (t.startsWith('ل') && t.length > 2 && !LAM_WORDS.test(t)) return t
  return t.startsWith('ال') ? `ل${t.slice(1)}` : `ل${t}`
}
