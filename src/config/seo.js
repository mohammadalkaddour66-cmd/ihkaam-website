/* وصفٌ لا يقلّ عن 120 حرفاً ولا يزيد على 155: يُركَّب من القطع بالترتيب
   حتى يبلغ الحدّ الأدنى. القطعُ كلها من بيانات الصفحة نفسها (لا حشوَ عام). */
export function composeDescription(parts, min = 125) {
  let out = ''
  for (const part of parts.filter(Boolean)) {
    out = out ? `${out.replace(/[.،]\s*$/, '')} — ${part}` : part
    if (out.length >= min) break
  }
  return clampDescription(out)
}
