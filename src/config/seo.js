const MAX_TITLE = 60
const MAX_DESC  = 155

/* تُذيَّل العلامةُ إن لم يحملها العنوان ولم يتجاوز الطولُ 60 حرفاً. */
export function buildTitle(title) {
  if (title.includes(SITE.brand)) return title
  const withBrand = `${title} | ${SITE.brand}`
  return withBrand.length <= MAX_TITLE ? withBrand : title
}

/* يقصّ الوصف الأطول من 155 حرفاً عند آخر كلمةٍ كاملة. */
export function clampDescription(text) {
  if (!text) return text
  const t = text.replace(/\s+/g, ' ').trim()
  if (t.length <= MAX_DESC) return t
  const cut = t.slice(0, MAX_DESC - 1)
  return cut.slice(0, cut.lastIndexOf(' ')).replace(/[،,:؛-]\s*$/, '') + '…'
}

/* الرابط المعياري: أصلٌ واحد ثابت + المسار بلا شرطة ختامية ولا معطيات استعلام. */
export function canonicalFor(pathname) {
  const clean = pathname.replace(/\/+$/, '')
  return SITE.origin + (clean || '/')
}

