/* عنوان البحث ووصفه وصورة المشاركة لمقالٍ واحد.
   الترتيب: حقول المقال نفسه ← الجدول أعلاه ← عنوان العرض ومقتطفه.
   الوصف الاحتياطي يُركَّب من المقتطف وأول فقرة حتى لا يقصر عن 120 حرفاً،
   والصورة غلافُ المقال إن كان له غلاف (cover) وإلا صورة الموقع العامة. */
export function blogSeo(post) {
  const fixed = BLOG_SEO[post.slug]
  const firstText = post.sections?.find(s => typeof s.text === 'string')?.text
  const cover = post.cover || post.image
  return {
    title: post.seoTitle || fixed?.title || post.title,
    description:
      post.seoDescription || fixed?.description ||
      composeDescription([post.excerpt, firstText?.split(/\n/)[0]]),
    image: cover ? (cover.startsWith('http') ? cover : SITE.origin + cover) : SITE.ogImage,
    /* النص البديل يصف صورة المقال نفسها لا صورة الموقع العامة (ISS-08). */
    imageAlt: cover ? `غلاف مقال «${post.title}» من مدونة إحكام` : undefined,
  }
}

