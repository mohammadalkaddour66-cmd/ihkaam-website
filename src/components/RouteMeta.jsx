import { useLocation } from 'react-router-dom'
import PageMeta from './PageMeta'
import { ROUTE_SEO } from '../config/seo'

/* ══════════════════════════════════════════════════════════════════
   وسومُ الصفحات الثابتة، مركَّبةً مرةً واحدة في Layout.

   البديل كان استدعاء <PageMeta> يدوياً في ثماني صفحات، ونسيانُه في
   التاسعة يمرّ بلا أثرٍ مرئي — وهذا بالضبط ما حصل: صفحاتٌ كـ /ihkaam
   و /about بقيت سنةً كاملة بعنوان الصفحة الرئيسية ووصفها.

   يعمل على المطابقة الحرفية للمسار فقط. المسارات المتغيّرة (مقالة،
   ميزة، مقالة مساعدة) غائبةٌ عن ROUTE_SEO عمداً، فيُرجِع null ولا
   يمسّ شيئاً — وتبقى كل صفحةٍ منها سيّدةَ وسومها.

   والترتيب مضمون: هذا المكوّن يسبق <Outlet/> في شجرة Layout، وReact
   يُنفّذ التأثيرات بترتيب الشجرة — فلو تصادف مسارٌ له مدخلٌ هنا
   ووسومٌ في صفحته، كتبت الصفحةُ بعده فغلبت. الأخصُّ يفوز.
   ══════════════════════════════════════════════════════════════════ */

export default function RouteMeta() {
  const { pathname } = useLocation()
  const key   = pathname.replace(/\/+$/, '') || '/'
  const entry = ROUTE_SEO[key]

  if (!entry) return null
  return <PageMeta {...entry} />
}
